(async()=>{
  const B=globalThis.BS;
  const report=result=>webkit.messageHandlers.qaResult.postMessage(result);
  const assert=(condition,message)=>{if(!condition)throw Error(message);};
  const click=selector=>{
    const button=document.querySelector(selector);
    assert(button&&!button.disabled,'Unavailable control '+selector);
    button.click();
  };
  await B.ready;
  const unpainted=await B.rasterize('<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20"><rect width="20" height="20" fill="white"/><rect x="4" y="4" width="12" height="12" fill="none" stroke="black" stroke-width="0"/><path d="M1 1L19 19" fill="none" stroke="black" stroke-width="0"/></svg>',20,20);
  assert(unpainted.getContext('2d').getImageData(0,0,20,20).data.every(v=>v===255),'Zero-width strokes left raster marks');
  const fixture=B.syntheticProject();
  await B.openProject(new File([JSON.stringify(fixture)],'SYNTHETIC-chart.wbproj'));
  click('[data-action="tab"][data-id="stats"]');
  const metric=document.querySelector('[data-scope="ui"][data-field="metric"]');
  metric.value='corrected';
  metric.dispatchEvent(new Event('change',{bubbles:true}));
  const data=B.currentStats();
  assert(data.groups.length>=2&&!data.error,'Fixture must contain independently measured groups');
  const original=B.getGroup().objects.length,sourceCount=B.state.p.sources.length;
  const chart=B.statsChartSVG(data),expected=new DOMParser().parseFromString(chart,'image/svg+xml');
  const samples=expected.querySelectorAll('circle').length;
  assert(samples>=data.rows.length,'Preview lost individual values');
  click('[data-action="chart-to-layout"]');
  assert(B.state.ui.tab==='edit','Did not switch to the layout');
  const group=B.getGroup(),project=B.state.p,added=group.objects.slice(original);
  assert(project.sources.length===sourceCount,'Chart was inserted as a source photograph');
  assert(added.length===B.state.ui.selected.length&&new Set(added.map(o=>o.groupId)).size===1,'Chart marks were not selected as one group');
  const points=added.filter(o=>o.geometry==='ellipse');
  assert(points.length===samples&&added.some(o=>o.type==='text'),'Editable points and text missing');
  const actual=B.svg(project,group,added);
  assert(new DOMParser().parseFromString(actual,'image/svg+xml').querySelectorAll('ellipse').length===samples,'Lost vector samples in SVG');
  const c=await B.rasterize(actual,group.canvas.width,group.canvas.height),point=points[0];
  const rgba=c.getContext('2d').getImageData(Math.round(point.x+point.w/2),Math.round(point.y+point.h/2),1,1).data;
  assert(rgba[3]===255&&Math.min(...rgba.slice(0,3))<235,'Lost sample color in the raster export');
  const pptx=new TextDecoder().decode(await B.pptx(project,{...group,objects:added}));
  assert((pptx.match(/prst="ellipse"/g)||[]).length===samples&&pptx.includes('<a:t '),'PowerPoint lost editable points or text');
  const snapshot=JSON.stringify(project);
  B.performUndo(false);
  assert(B.getGroup().objects.length===original,'Undo changed the source layout');
  B.performUndo(true);
  assert(B.getGroup().objects.length===original+added.length,'Redo lost chart marks');
  await B.openProject(new File([snapshot],'SYNTHETIC-chart-roundtrip.wbproj'));
  assert(B.getGroup().objects.filter(o=>o.geometry==='ellipse').length===samples,'Reopen lost editable points');
  report({name:'editable statistical chart',passed:1,total:1,tests:[{name:'Statistics page to editable layout, SVG, raster, PowerPoint and project reopen',pass:true}],observations:{groups:data.groups.length,values:data.rows.length,vectorPoints:samples,editableMarks:added.length,centerPixel:Array.from(rgba)}});
})().catch(error=>webkit.messageHandlers.qaResult.postMessage({fatal:error.message,stack:error.stack}));
